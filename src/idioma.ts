// Spanish / English. The Spanish text is the key, so the code reads naturally and Spanish needs no table; every other
// language is a map from that text. Pure, so it runs under `node --test` (idioma.test.ts checks nothing is left untranslated).
export type Lang = 'es' | 'en';
export type PreferenciaIdioma = 'auto' | Lang; // 'auto' follows the phone
export type T = (clave: string, params?: Record<string, string | number>) => string;

export const esPreferenciaIdioma = (x: string): x is PreferenciaIdioma => x === 'auto' || x === 'es' || x === 'en';

// `locale` is the phone's, e.g. "es-CO" or "en-US".
export const resolverIdioma = (pref: PreferenciaIdioma, locale: string): Lang =>
  pref === 'es' || pref === 'en' ? pref : locale.toLowerCase().startsWith('es') ? 'es' : 'en';

export const idiomaDelSistema = () => {
  try { return Intl.DateTimeFormat().resolvedOptions().locale; } catch { return 'es'; }
};

const interpolar = (s: string, p?: Record<string, string | number>) =>
  p ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in p ? String(p[k]) : m)) : s;

export const crearT = (lang: Lang): T => {
  const dic = lang === 'en' ? EN : undefined;
  return (clave, params) => interpolar(dic?.[clave] ?? clave, params);
};

