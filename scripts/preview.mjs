// Builds docs/preview/index.html (and docs/img/mascotas.png if a Chromium-based browser is installed) from the
// drawings in src/Mascota.tsx, so the pictures in the README can never drift from what the app shows.
// Run: npm run preview
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

const raiz = new URL('../', import.meta.url);

const kebab = (s) => s.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`); // strokeWidth -> stroke-width
const alfa = (hex, a) => `rgba(${[1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)).join(',')},${a})`;

// JSX <Path d="..." fill="#fff" strokeWidth={3} /> -> SVG <path d="..." fill="#fff" stroke-width="3"/>
function aSvg(jsx) {
  return [...jsx.matchAll(/<(Path|Circle|Rect)\s+([^>]*?)\/>/g)].map(([, tag, attrs]) => {
    const a = [...attrs.matchAll(/(\w+)=(?:"([^"]*)"|\{([^}]*)\})/g)].map(([, k, s, n]) => `${kebab(k)}="${s ?? n}"`);
    return `<${tag.toLowerCase()} ${a.join(' ')}/>`;
  }).join('');
}

export function generarHtml(mascotaTsx, mascotasTs) {
  const rosa = mascotaTsx.match(/const ROSA = alfa\('(#[0-9A-Fa-f]{6})', ([\d.]+)\)/);
  const color = (v) => (v.trim() === 'ROSA' ? alfa(rosa[1], rosa[2]) : v.replace(/alfa\('(#[0-9A-Fa-f]{6})', ([\d.]+)\)/, (_, h, n) => alfa(h, n)));
  const nombres = Object.fromEntries([...mascotasTs.matchAll(/id: '(\w+)', nombre: '([^']+)'/g)].map((m) => [m[1], m[2]]));
  const cuerpos = [...mascotaTsx.matchAll(/^ {2}(\w+): \{\n {4}dibujo: \(\n([\s\S]*?)\n {4}\),\n {4}cara: \{ ([^\n]*) \},\n {2}\},/gm)];
  if (!cuerpos.length) throw new Error('No mascot drawings found in Mascota.tsx (did its layout change?)');

  const tarjetas = cuerpos.map(([, id, dibujo, cara]) => {
    const c = Object.fromEntries([...cara.matchAll(/(\w+): ('[^']*'|alfa\([^)]*\)|[\w.]+)/g)].map(([, k, v]) => [k, v.replace(/^'|'$/g, '')]));
    const x = +c.x, y = +c.y, sep = +c.sep, m = color(c.mejilla);
    const rostro =
      `<circle cx="${x - sep / 2 - 5}" cy="${y + 7}" r="3.6" fill="${m}"/><circle cx="${x + sep / 2 + 5}" cy="${y + 7}" r="3.6" fill="${m}"/>` +
      `<ellipse cx="${x - sep / 2}" cy="${y}" rx="3.4" ry="3.6" fill="${c.color}"/><ellipse cx="${x + sep / 2}" cy="${y}" rx="3.4" ry="3.6" fill="${c.color}"/>` +
      `<path d="M${x - 6} ${y + 7} Q${x} ${y + 13} ${x + 6} ${y + 7}" stroke="${c.color}" stroke-width="2.6" stroke-linecap="round" fill="none"/>`;
    return `    <figure><svg viewBox="0 0 100 100" role="img" aria-label="${nombres[id]}">${aSvg(dibujo)}${rostro}</svg><figcaption>${nombres[id]}</figcaption></figure>`;
  });

  return `<!doctype html>
<html lang="es">
<head>
  <meta charset="utf-8">
  <title>Mascotas de Vento</title>
  <!-- Only to take the preview pictures of the README. Generated by scripts/preview.mjs: do not edit by hand. -->
  <style>
    @font-face { font-family: Lexend; font-weight: 600; src: url(../../node_modules/@expo-google-fonts/lexend/600SemiBold/Lexend_600SemiBold.ttf); }
    body { margin: 0; background: #fff; font-family: Lexend, system-ui, sans-serif; }
    main { display: grid; grid-template-columns: repeat(3, 260px); gap: 24px; justify-content: center; padding: 40px; }
    figure { margin: 0; background: #f3f6f4; border-radius: 28px; padding: 28px 0 24px; text-align: center; }
    svg { width: 170px; height: 170px; }
    figcaption { margin-top: 8px; font-size: 26px; font-weight: 600; color: #10261a; }
  </style>
</head>
<body>
  <main>
${tarjetas.join('\n')}
  </main>
</body>
</html>
`;
}

// `node scripts/preview.mjs`: write the page, then try to take the picture with whichever browser is installed.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const html = generarHtml(readFileSync(new URL('src/Mascota.tsx', raiz), 'utf8'), readFileSync(new URL('src/mascotas.ts', raiz), 'utf8'));
  const ruta = fileURLToPath(new URL('docs/preview/index.html', raiz));
  writeFileSync(ruta, html);
  console.log('Wrote docs/preview/index.html');
  const navegador = ['google-chrome-stable', 'google-chrome', 'chromium', 'chromium-browser', 'brave'].find((n) => spawnSync('which', [n]).status === 0);
  if (!navegador) console.log('No Chromium-based browser found: open the page and take the picture by hand.');
  else {
    const png = fileURLToPath(new URL('docs/img/mascotas.png', raiz));
    const r = spawnSync(navegador, ['--headless', '--disable-gpu', '--hide-scrollbars', `--screenshot=${png}`, '--window-size=1000,640', pathToFileURL(ruta).href]);
    console.log(r.status === 0 ? 'Wrote docs/img/mascotas.png' : `The browser failed (${r.status})`);
  }
}
